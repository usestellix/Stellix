// Regenerates the key-derivation test vectors in packages/core/src/keys/__tests__/ from the
// published specs. Each spec is fetched at a pinned commit and its SHA-256 verified, so vectors
// are copied mechanically and verbatim (KEY_MANAGEMENT §2: never generate expected values).
//
// Usage: node scripts/extract-test-vectors.mjs
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const DIR = "packages/core/src/keys/__tests__";

const SEP0005 = {
  commit: "ece6a7974b918091283d637af039f8117d94bc5d",
  sha256: "62f152c5574c908161e1a213f487bf9d1b5b4fa21d616eab107bf58b9604a307",
  url: (/** @type {string} */ c) =>
    `https://raw.githubusercontent.com/stellar/stellar-protocol/${c}/ecosystem/sep-0005.md`,
  page: (/** @type {string} */ c) =>
    `https://github.com/stellar/stellar-protocol/blob/${c}/ecosystem/sep-0005.md`,
};

const SLIP0010 = {
  commit: "a00312491693714d9bc1b6e4cb5b2e356e6c511e",
  sha256: "dbd5a324f2a6014bf78fc8cfa85833e4a16256a02283b93d648fccba18ed1ce7",
  url: (/** @type {string} */ c) =>
    `https://raw.githubusercontent.com/satoshilabs/slips/${c}/slip-0010.md`,
  page: (/** @type {string} */ c) => `https://github.com/satoshilabs/slips/blob/${c}/slip-0010.md`,
};

/** @param {{ commit: string; sha256: string; url: (c: string) => string }} spec */
async function fetchVerified(spec) {
  const res = await fetch(spec.url(spec.commit));
  if (!res.ok) throw new Error(`Fetch failed: ${String(res.status)}`);
  const text = await res.text();
  const digest = createHash("sha256").update(text).digest("hex");
  if (digest !== spec.sha256) throw new Error(`Spec hash mismatch: ${digest}`);
  return text;
}

/** @param {{ commit: string; sha256: string; page: (c: string) => string }} spec */
function header(spec) {
  return `// GENERATED by scripts/extract-test-vectors.mjs — do not edit by hand.
// Source: ${spec.page(spec.commit)}
// Spec SHA-256: ${spec.sha256}
`;
}

// ---- SEP-0005 ----
{
  const text = await fetchVerified(SEP0005);
  const sections = text.split(/^### Test (\d+)\s*$/m).slice(1);
  const vectors = [];
  for (let i = 0; i < sections.length; i += 2) {
    const test = Number(sections[i]);
    const body = sections[i + 1] ?? "";
    const blocks = [...body.matchAll(/```\n([\s\S]*?)\n```/g)].map((m) => m[1] ?? "");
    const [phraseBlock = "", seedBlock = "", , keysBlock = ""] = blocks;
    const [mnemonic = "", passphrase = ""] = phraseBlock.split(/\n\s*\n/).map((s) => s.trim());
    const accounts = keysBlock
      .split("\n")
      .map((line) => line.trim().split(/\s+/))
      .map(([path = "", publicKey = "", secretKey = ""]) => {
        const m = /^m\/44'\/148'\/(\d+)'$/.exec(path);
        if (m === null) throw new Error(`SEP-0005 test ${String(test)}: unexpected path ${path}`);
        return { index: Number(m[1]), publicKey, secretKey };
      });
    if (accounts.length !== 10)
      throw new Error(`SEP-0005 test ${String(test)}: expected 10 accounts`);
    vectors.push({ test, mnemonic, passphrase, seedHex: seedBlock.trim(), accounts });
  }
  if (vectors.length !== 5)
    throw new Error(`Expected 5 SEP-0005 tests, got ${String(vectors.length)}`);

  writeFileSync(
    `${DIR}/sep0005.vectors.ts`,
    `${header(SEP0005)}
export interface Sep0005Vector {
  test: number;
  mnemonic: string;
  /** BIP39 passphrase ("" when the vector has none). */
  passphrase: string;
  seedHex: string;
  accounts: readonly { index: number; publicKey: string; secretKey: string }[];
}

export const SEP0005_VECTORS: readonly Sep0005Vector[] = ${JSON.stringify(vectors, null, 2)};
`,
  );
  process.stdout.write(`SEP-0005: ${String(vectors.length)} tests\n`);
}

// ---- SLIP-0010 (ed25519 sections only) ----
{
  const text = await fetchVerified(SLIP0010);
  const sections = text.split(/^### Test vector (\d+) for (\S+)\s*$/m).slice(1);
  const vectors = [];
  for (let i = 0; i < sections.length; i += 3) {
    const test = Number(sections[i]);
    const curve = sections[i + 1];
    const body = sections[i + 2] ?? "";
    if (curve !== "ed25519") continue;
    const seedHex = /Seed \(hex\): ([0-9a-f]+)/.exec(body)?.[1];
    if (seedHex === undefined) throw new Error(`SLIP-0010 test ${String(test)}: no seed`);
    const chains = body
      .split(/^\* Chain /m)
      .slice(1)
      .map((chain) => {
        const path = (chain.split("\n")[0] ?? "").trim().replaceAll("<sub>H</sub>", "'");
        const field = (/** @type {string} */ name) => {
          const v = new RegExp(`\\* ${name}: ([0-9a-f]+)`).exec(chain)?.[1];
          if (v === undefined)
            throw new Error(`SLIP-0010 test ${String(test)} ${path}: no ${name}`);
          return v;
        };
        return {
          path,
          chainCode: field("chain code"),
          privateKey: field("private"),
          publicKey: field("public"),
        };
      });
    vectors.push({ test, seedHex, chains });
  }
  if (vectors.length !== 2)
    throw new Error(`Expected 2 SLIP-0010 ed25519 tests, got ${String(vectors.length)}`);

  writeFileSync(
    `${DIR}/slip0010.vectors.ts`,
    `${header(SLIP0010)}
export interface Slip0010Vector {
  test: number;
  seedHex: string;
  /** Hex. \`publicKey\` is SLIP-0010's serialization: 0x00 followed by the 32-byte ed25519 key. */
  chains: readonly { path: string; chainCode: string; privateKey: string; publicKey: string }[];
}

/** SLIP-0010 test vectors for ed25519 only. */
export const SLIP0010_ED25519_VECTORS: readonly Slip0010Vector[] = ${JSON.stringify(vectors, null, 2)};
`,
  );
  process.stdout.write(`SLIP-0010 ed25519: ${String(vectors.length)} tests\n`);
}

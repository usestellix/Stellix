// Runs after `next build` (see the build script). Finishes the static export in out/:
//
// 1. Before Shield launches (no S1 capability shipped), removes the phase 2 pages, so phase 1
//    publishes only the home page, /privacy and the 404 page. Their HTML, RSC payloads and
//    folders all go: a request for one gets the 404 page with a 404 status.
// 2. Writes out/_headers for Cloudflare Pages: one strict CSP for every path, whose script-src
//    allows 'self' plus the SHA-256 of each inline script Next.js emitted on any published page.
//
// Why one site-wide policy: Cloudflare joins a header set by two matching rules with a comma,
// and two CSPs are both enforced. A single `/*` rule avoids that, and the union of hashes is
// small (Next.js emits three inline scripts per page). Inline styles and style attributes would
// need 'unsafe-inline' or hashes; the build fails if either appears.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadStatus } from "./lib/load-status.mjs";

const OUT = path.resolve(import.meta.dirname, "../out");
const { SHIELD_LAUNCHED, PHASE2_PAGES } = await loadStatus();

// 1. Launch phase.
if (!SHIELD_LAUNCHED) {
  for (const { href } of PHASE2_PAGES) {
    const base = path.join(OUT, href.slice(1));
    for (const p of [`${base}.html`, `${base}.txt`, base]) {
      if (existsSync(p)) rmSync(p, { recursive: true });
    }
  }
  process.stdout.write(
    `postbuild: phase 1, removed ${PHASE2_PAGES.map((p) => p.href).join(", ")}\n`,
  );
} else {
  process.stdout.write("postbuild: phase 2, all pages published\n");
}

// 2. Content-Security-Policy and the other headers.
function htmlFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) return htmlFiles(p);
    return p.endsWith(".html") ? [p] : [];
  });
}

const sha256 = (text) => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;
const scriptHashes = new Set();
const problems = [];

for (const file of htmlFiles(OUT)) {
  const html = readFileSync(file, "utf8");
  const rel = path.relative(OUT, file);
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
    scriptHashes.add(sha256(m[1] ?? ""));
  }
  if (/<style[\s>]/.test(html)) problems.push(`${rel}: inline <style> element`);
  if (/<[^>]+\sstyle="/.test(html)) problems.push(`${rel}: style attribute`);
}

if (problems.length > 0) {
  for (const p of problems) process.stderr.write(`postbuild: ${p}\n`);
  process.stderr.write("postbuild: inline styles would need a weaker CSP; remove them\n");
  process.exit(1);
}

const CSP = [
  "default-src 'self'",
  `script-src 'self' ${[...scriptHashes].sort().join(" ")}`,
  "style-src 'self'",
  "img-src 'self'",
  "font-src 'self'",
  "connect-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

const PERMISSIONS = [
  "accelerometer",
  "camera",
  "display-capture",
  "geolocation",
  "gyroscope",
  "hid",
  "magnetometer",
  "microphone",
  "payment",
  "serial",
  "usb",
  "browsing-topics",
]
  .map((feature) => `${feature}=()`)
  .join(", ");

const RULES = [
  [
    "/*",
    {
      "Content-Security-Policy": CSP,
      "Strict-Transport-Security": "max-age=63072000; includeSubDomains",
      "X-Content-Type-Options": "nosniff",
      "Referrer-Policy": "no-referrer",
      "Permissions-Policy": PERMISSIONS,
      "X-Frame-Options": "DENY",
      "Cross-Origin-Opener-Policy": "same-origin",
      "Cross-Origin-Resource-Policy": "same-origin",
    },
  ],
  // Hashed file names: safe to cache forever.
  ["/_next/static/*", { "Cache-Control": "public, max-age=31536000, immutable" }],
  // Exported without an extension; nosniff needs the type stated.
  ["/opengraph-image", { "Content-Type": "image/png" }],
];

// Cloudflare limits: 100 rules, 2,000 characters per line.
const lines = RULES.flatMap(([pattern, headers]) => [
  pattern,
  ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`),
]);
const tooLong = lines.filter((l) => l.length > 2000);
if (RULES.length > 100 || tooLong.length > 0) {
  process.stderr.write(
    `postbuild: _headers exceeds Cloudflare's limits (${tooLong.length} long lines)\n`,
  );
  process.exit(1);
}

writeFileSync(
  path.join(OUT, "_headers"),
  `# Generated by scripts/postbuild.mjs. Do not edit; rebuild instead.\n${lines.join("\n")}\n`,
);
process.stdout.write(
  `postbuild: _headers written, ${scriptHashes.size} inline script hashes, CSP ${CSP.length} chars\n`,
);
